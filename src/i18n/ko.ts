/** ko 를 기준으로 한 문자열 테이블 타입. 함수 시그니처까지 같아야 한다. */
type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => R
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T extends string
        ? string
        : T;

export type Strings = Widen<typeof ko>;
