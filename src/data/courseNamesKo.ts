/** 한국어 모드 과목명. 기호·끝 번호(Ⅰ~Ⅵ, A/B, [再])는 그대로 붙이고, 사전에 없으면 원문 */
export function courseNameFor(name: string | null | undefined, locale: string): string {
  if (!name) return '';
  if (locale !== 'ko') return name;
  const m = /^([□※◇＊]*)(.*?)((?:\s*[ⅠⅡⅢⅣⅤⅥ])?(?:\s*[AＡBＢ])?(?:\[再\])?)$/.exec(name);
  if (!m) return name;
  const [, mark, body, tail] = m;
  const ko = COURSE_KO[body.trim()];
  return ko ? `${mark}${ko}${tail.replace('[再]', ' [재수강]').replace('Ａ', 'A').replace('Ｂ', 'B')}` : name.replace('[再]', ' [재수강]');
}
