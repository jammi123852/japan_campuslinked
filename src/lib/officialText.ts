const JA_FIX: [string, string][] = [['기준', '基準'], ['표본', '標本'], ['추가조사', '追加調査'], ['게시본', '掲示版']];

const JAPANESE = /[぀-ヿ一-鿿]/;

export function officialText(text: string | null | undefined, locale: string, fallback?: string): string {
  if (!text) return '';
  // 일본어 모드: 자료 제목에 섞인 한국어 메모를 일본어로
  if (locale !== 'ko') return JA_FIX.reduce((acc, [ko, ja]) => acc.split(ko).join(ja), text);
  let s = text;
  for (const [re, ko] of SENTENCES) s = s.replace(re, ko);
  const org = Object.entries(ORG_KO).sort((a, b) => b[0].length - a[0].length);
  for (const [ja, ko] of org) s = s.split(ja).join(ko);
  for (const [ja, ko] of PHRASES) s = s.split(ja).join(ko);
  s = s.replace(/\s{2,}/g, ' ').trim();
  return JAPANESE.test(s) ? (fallback ?? s) : s;
}

const DAY_KO: Record<string, string> = { 月: '월', 火: '화', 水: '수', 木: '목', 金: '금', 土: '토', 日: '일' };

/** 공식 자료의 요일·교시 표기('木３', '月1・水2')를 한국어 모드에서 '목 3' 처럼 바꾼다 */
export function weekdayPeriod(wp: string | null | undefined, locale: string): string {
  if (!wp) return '';
  if (locale !== 'ko') return wp;
  return wp
    .replace(/[０-９]/g, (d) => String.fromCharCode(d.charCodeAt(0) - 0xfee0))
    .replace(/[月火水木金土日]/g, (d) => `${DAY_KO[d]} `)
    .replace(/・/g, ', ')
    .replace(/\s+,/g, ',')
    .trim();
}
